    private void auto_id() {
      try {
        Connection conn = koneksi.getKoneksi();
        Statement st = conn.createStatement();
        ResultSet rs = st.executeQuery("SELECT id_layanan FROM layanan ORDER BY id_layanan DESC LIMIT 1");

        String id = "LY001"; // default kalau kosong

        if (rs.next()) {
            String lastID = rs.getString("id_layanan");

            if (lastID != null && lastID.length() >= 3) {
                String angka = lastID.substring(2); // ambil angka
                int no = Integer.parseInt(angka) + 1;
                id = "LY" + String.format("%03d", no);
            }
        }

        txtid.setText(id);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "AutoID gagal: " + e.getMessage());
    }
}
    
    private void tampil_data() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID");
    model.addColumn("Jenis Layanan");
    model.addColumn("Harga");

    try {
        String sql = "SELECT * FROM layanan";
        Connection conn = koneksi.getKoneksi();
        java.sql.Statement stm = conn.createStatement();
        ResultSet res = stm.executeQuery(sql);

        while (res.next()) {
            model.addRow(new Object[]{
                res.getString("id_layanan"),
                res.getString("nama_layanan"),
                res.getString("harga_per_kg")
            });
        }

        jtabel.setModel(model);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Gagal tampil data: " + e.getMessage());
    }
}


    private void btnsimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsimpanActionPerformed
        // TODO add your handling code here:
          try {
        if (txtjenis.getText().isEmpty() || txthrg.getText().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Data tidak boleh kosong!");
        return;
}
        int harga = Integer.parseInt(txthrg.getText());
        String sql = "INSERT INTO layanan (id_layanan, nama_layanan, harga_per_kg) VALUES (?,?,?)";

        Connection conn = koneksi.getKoneksi();
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, txtid.getText());
        pst.setString(2, txtjenis.getText());
        pst.setString(3, txthrg.getText());

        pst.executeUpdate();
        JOptionPane.showMessageDialog(null, "Data berhasil disimpan");
        tampil_data();
        txtjenis.setText("");
        txthrg.setText("");
        auto_id();

        txtjenis.setText("");
        txthrg.setText("");

} catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Gagal simpan: " + e.getMessage());
    }
    }//GEN-LAST:event_btnsimpanActionPerformed

